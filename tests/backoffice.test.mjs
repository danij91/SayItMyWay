import {loadKorean} from './i18n-harness.mjs';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,copyFile,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {JSDOM} from 'jsdom';
import {createServer} from '../server.mjs';
test('backoffice renders, searches, adds and edits via real local API',async()=>{
  const dir=await mkdtemp(path.join(os.tmpdir(),'crimson-ui-'));
  const dataPath=path.join(dir,'dictionary.json');
  await copyFile(new URL('../extension/data/dictionary.json',import.meta.url),dataPath);
  const seed=JSON.parse(await readFile(dataPath,'utf8'));
  const server=await createServer({dataPath});await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const base='http://127.0.0.1:'+server.address().port;
  let d;
  try {
    d=new JSDOM(await(await fetch(base)).text(),{url:base,runScripts:'outside-only'});
    const w=d.window,$=s=>w.document.querySelector(s);
    loadKorean(w);w.structuredClone=structuredClone;
    w.fetch=(url,options={})=>fetch(new URL(url,base),{...options,headers:{...options.headers,...(options.method?{Origin:base}:{})}});
    w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
    w.HTMLDialogElement.prototype.close=function(){this.open=false;};
    for(const file of ['extension/shared.js','extension/library.js','extension/editor/transport.js','extension/import-ui.js','extension/editor/app.js'])w.eval(await readFile(new URL('../'+file,import.meta.url),'utf8'));
    const until=async predicate=>{for(let i=0;i<100;i++){if(predicate())return;await new Promise(r=>setTimeout(r,10));}throw Error('UI timeout');};
    const input=(id,value)=>{$(id).value=value;$(id).dispatchEvent(new w.Event('input'));};
    await until(()=>$('#rows').children.length===seed.entries.length);
    input('#query','파이웰');assert.equal($('#rows').children.length,1);assert.match($('#rows').textContent,/Pywel/);
    input('#query','');assert.equal($('#status'),null);
    assert.equal($('#category'),null);assert.equal($('#kind'),null);$('#add').click();
    const form=$('#form');for(const [key,value] of Object.entries({en:'UI test',ko:'화면 테스트'}))form.elements[key].value=value;
    form.dispatchEvent(new w.Event('submit',{cancelable:true}));await until(()=>!$('#editor').open);
    input('#query','UI test');assert.match($('#rows').textContent,/화면 테스트/);
    $('#rows button').click();form.elements.ko.value='수정 테스트';
    form.dispatchEvent(new w.Event('submit',{cancelable:true}));await until(()=>!$('#editor').open);
    assert.match($('#rows').textContent,/수정 테스트/);
    assert.equal((await (await fetch(base+'/api/library')).json()).tables[0].entries.length,seed.entries.length);
    await $('#save-all').onclick();
    const persisted=await (await fetch(base+'/api/library')).json();assert.equal(persisted.tables[0].entries.at(-1).ko,'수정 테스트');
    $('#table-create').click();$('#table-name').value='새 표';$('#table-form').dispatchEvent(new w.Event('submit',{cancelable:true}));
    await until(()=>$('#table-select').options.length===2);assert.equal($('#table-select').selectedOptions[0].textContent,'새 표');
    $('#add').click();for(const [key,value] of Object.entries({en:'Hello',ko:'안녕'}))form.elements[key].value=value;
    form.dispatchEvent(new w.Event('submit',{cancelable:true}));await until(()=>!$('#editor').open);
    input('#query','');assert.match($('#rows').textContent,/Hello/);
    assert.equal($('#defaults-match'),null);assert.equal(form.elements.matchMode,undefined);assert.equal(form.elements.caseSensitive,undefined);
    $('#table-copy').click();$('#table-name').value='복사본';$('#table-form').dispatchEvent(new w.Event('submit',{cancelable:true}));await until(()=>$('#table-select').options.length===3);
    assert.match($('#rows').textContent,/Hello/);
    $('#table-rename').click();$('#table-name').value='새 이름';$('#table-form').dispatchEvent(new w.Event('submit',{cancelable:true}));await until(()=>$('#table-select').selectedOptions[0].textContent==='새 이름');
    w.confirm=()=>true;$('#rows button[data-delete]').click();await until(()=>!$('#rows').textContent.includes('Hello'));
    await $('#save-all').onclick();
    const final=await (await fetch(base+'/api/library')).json();assert.equal(final.tables[1].entries[0].matchMode,undefined);assert.equal(final.tables[1].entries[0].caseSensitive,undefined);assert.deepEqual(final.tables[2].defaults,{matchMode:'exact',caseSensitive:false,translatePlaceholders:true});assert.equal(final.tables[2].entries.length,0);
    assert.deepEqual(JSON.parse(await readFile(dataPath,'utf8')),seed);
  }finally{d?.window.close();await new Promise(r=>server.close(r));await rm(dir,{recursive:true,force:true});}
});
